-- 공동보호자 초대의 직접 INSERT 권한 회수 — 계정 열거 차단의 **실효화** (0032 §9.2).
--
-- invite-guardian 엣지 함수는 "이 번호가 가입자인가" 를 알려 준다. 그 자체가 회원 여부
-- 오라클이라 레이트리밋을 걸어 시도 횟수를 묶는 게 이번 조치인데, 그 리밋은 엣지 함수
-- 안에만 있다. 그런데 `pgi_insert` 정책이 인증 사용자에게 직접 INSERT 를 허용한다 —
-- 펫 owner 면 PostgREST 로 초대 행을 바로 넣을 수 있고,
--
--   · BEFORE 트리거(tg_pgi_resolve_invitee)가 번호로 가입자를 찾아 invitee_user_id 를 채우고
--   · `pgi_select` 가 초대자에게 그 행을 보여 준다
--
-- 즉 **엣지 함수를 거치지 않고, 리밋도 없이, 같은 사실을 무제한으로 캐낼 수 있었다.**
-- 함수에만 건 검증은 검증이 아니다(0031 §자기초대 사례와 같은 구조).
--
-- 실사용 확인 후 닫는다:
--   · 앱은 이 테이블에 INSERT 하지 않는다(초대는 전부 엣지 함수 경유, 조회·응답만 직접).
--   · `kind='request'`(가입 요청) 흐름은 설계만 있고 UI 가 없다 — 운영 데이터 0건.
--   · 운영 전체 초대 행은 1건(kind='invite', 2026-07-18)뿐이다.
--   · 엣지 함수는 service_role 이라 이 그랜트와 무관하게 계속 넣는다.
--
-- 정책(`pgi_insert`)은 지우지 않고 남긴다. 지금은 도달할 수 없지만, 그랜트가 되살아나는
-- 날에도 "본인 명의 + owner" 조건은 남아 있어야 한다 — 방어를 한 겹으로 줄이지 않는다.
revoke insert on public.pet_guardian_invites from authenticated, anon;
